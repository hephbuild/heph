    fn spec(libs: &[(String, Addr)], facts: &[(String, Addr)]) -> TargetSpec {
        spec_cfg(libs, facts, None)
    }

    fn spec_cfg(
        libs: &[(String, Addr)],
        facts: &[(String, Addr)],
        config_addr: Option<&Addr>,
    ) -> TargetSpec {
        let g = govet();
        build_lint_spec(LintParams {
            addr: addr("lint"),
            import_path: "example.com/mylib",
            factors: &factors(),
            go_version: V,
            transitive_libs: libs,
            facts_libs: facts,
            src_addrs: &["//mylib:a.go".to_string()],
            govet_addr: &g,
            config_addr,
        })
    }

    fn deps_map(s: &TargetSpec) -> HashMap<String, Vec<String>> {
        match s.config.get("deps").unwrap() {
            Value::Map(m) => m
                .iter()
                .map(|(k, v)| {
                    let list = match v {
                        Value::List(l) => l
                            .iter()
                            .map(|x| match x {
                                Value::String(s) => s.clone(),
                                _ => panic!("dep entry not a string"),
                            })
                            .collect(),
                        _ => panic!("dep group not a list"),
                    };
                    (k.clone(), list)
                })
                .collect(),
            _ => panic!("deps not a map"),
        }
    }

