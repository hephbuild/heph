use hmodel::htaddr::Addr;
use hplugin::provider::TargetSpec;

/// Parameters for [`build_lint_spec`].
pub struct LintParams<'a> {
    pub addr: Addr,
    /// Import path of the package under analysis.
    pub import_path: &'a str,
    pub factors: &'a Factors,
    pub go_version: &'a str,
    /// `(import_path, build_lib archive addr)` — `lib_*` dep groups + cfg
    /// PackageFile entries (type info for every transitive dependency).
    pub transitive_libs: &'a [(String, Addr)],
    /// `(import_path, lint addr)` — `facts_*` dep groups; the deps whose facts
    /// feed interprocedural analysis. Subset of `transitive_libs` (e.g. omit
    /// stdlib until it is linted too).
    pub facts_libs: &'a [(String, Addr)],
    /// Compile sources (`.go`) → the default (`""`) dep group.
    pub src_addrs: &'a [String],
    /// `build` addr of the `heph-govet` unitchecker binary.
    pub govet_addr: &'a Addr,
    /// `.golangci.yml` file addr → `config` dep group, passed to heph-govet via
    /// `HEPH_GOVET_GOLANGCI_CONFIG`. `None` → the standard analyzer set.
    pub config_addr: Option<&'a Addr>,
}

/// Build a `go_lint` target spec.
pub fn build_lint_spec(p: LintParams) -> TargetSpec {
    let str_one = |a: &Addr| Value::List(vec![Value::String(a.format())]);

    let mut deps: BTreeMap<String, Value> = p
        .transitive_libs
        .iter()
        .map(|(import_path, dep_addr)| (import_path_to_dep_group(import_path), str_one(dep_addr)))
        .collect();
    for (import_path, lint_addr) in p.facts_libs {
        // `|facts` selects the analyze target's facts output ONLY. Without it the
        // whole `_lint-analyze` target stages — facts *and* `lint-report.json` — and the
        // consumer, which takes the single staged path of the group, gets whichever
        // sorts first: `lint-report.json` (`-` < `.`). unitchecker then gob-decodes
        // the JSON report as facts ("unexpected EOF"). The gate is explicit the same
        // way (`|report`).
        deps.insert(
            import_path_to_facts_group(import_path),
            Value::List(vec![Value::String(format!("{}|facts", lint_addr.format()))]),
        );
    }
    deps.insert(
        String::new(),
        Value::List(p.src_addrs.iter().cloned().map(Value::String).collect()),
    );
    deps.insert(GOVET_TOOL_GROUP.to_string(), str_one(p.govet_addr));
    if let Some(cfg) = p.config_addr {
        deps.insert("config".to_string(), str_one(cfg));
    }

    // Sorted for an order-independent cache key (see GoLintDef::hash).
    let mut import_paths: Vec<String> =
        p.transitive_libs.iter().map(|(ip, _)| ip.clone()).collect();
    import_paths.sort();
    let import_paths: Vec<Value> = import_paths.into_iter().map(Value::String).collect();

    let mut config: HashMap<String, Value> = HashMap::new();
    config.insert(
        "import_path".to_string(),
        Value::String(p.import_path.to_string()),
    );
    config.insert("goos".to_string(), Value::String(p.factors.goos.clone()));
    config.insert(
        "goarch".to_string(),
        Value::String(p.factors.goarch.clone()),
    );
    config.insert(
        "go_version".to_string(),
        Value::String(p.go_version.to_string()),
    );
    if !p.factors.build_tags.is_empty() {
        config.insert(
            "build_tags".to_string(),
            Value::List(
                p.factors
                    .build_tags
                    .iter()
                    .map(|t| Value::String(t.clone()))
                    .collect(),
            ),
        );
    }
    if !p.factors.goexperiment.is_empty() {
        config.insert(
            "goexperiment".to_string(),
            Value::List(
                p.factors
                    .goexperiment
                    .iter()
                    .map(|t| Value::String(t.clone()))
                    .collect(),
            ),
        );
    }
    config.insert("import_paths".to_string(), Value::List(import_paths));
    config.insert("deps".to_string(), Value::Map(deps.into_iter().collect()));
    config.insert(
        "out".to_string(),
        Value::Map(HashMap::from([
            (
                "facts".to_string(),
                Value::List(vec![Value::String(LINT_FACTS.to_string())]),
            ),
            (
                "report".to_string(),
                Value::List(vec![Value::String(LINT_REPORT.to_string())]),
            ),
        ])),
    );

    TargetSpec {
        addr: p.addr,
        driver: "go_lint".to_string(),
        config,
        // No labels: `_lint-analyze` is the analyze unit `lint` / `lint-check` consume, not
        // a target anyone selects. Labels are the selection surface, so it has none
        // — it is reached only as a dep.
        labels: vec![],
        transitive: Default::default(),
        approval: Default::default(),
    }
}

/// Build the user-facing `lint` gate spec. Depends on the `report` output of the
/// analyze target (`_lint-analyze`) and fails the build when it contains findings.
///
/// `config_addr` (the module's `.golangci.yml`) is attached as a hash-only dep
/// so any config change re-keys the gate directly — not just transitively
/// through `_lint-analyze`'s report.
pub fn build_lint_gate_spec(
    addr: Addr,
    analyze_addr: &Addr,
    config_addr: Option<&Addr>,
) -> TargetSpec {
    let mut deps = BTreeMap::from([(
        "report".to_string(),
        Value::List(vec![Value::String(format!(
            "{}|report",
            analyze_addr.format()
        ))]),
    )]);
    if let Some(cfg) = config_addr {
        deps.insert(
            "config".to_string(),
            Value::List(vec![Value::String(cfg.format())]),
        );
    }
    let mut config: HashMap<String, Value> = HashMap::new();
    config.insert("deps".to_string(), Value::Map(deps.into_iter().collect()));

    TargetSpec {
        addr,
        driver: "go_lint_gate".to_string(),
        config,
        // The read-only checker (`lint-check`): `go-lint-check` selects it among go
        // targets, `lint-check` selects every language's checker at once
        // (`--label lint-check //...`). The plain `lint` label belongs to the fixer.
        labels: vec!["go-lint-check".to_string(), "lint-check".to_string()],
        transitive: Default::default(),
        approval: Default::default(),
    }
}

/// Build the user-facing `lint` (fixer) spec. Depends on the `report` output of the
/// analyze target (`_lint-analyze`) plus the package's own `.go` sources, applies each
/// diagnostic's suggested fix, and rewrites the sources in place (codegen).
///
/// `src_addrs` are the source file target addresses (the `""` dep group, staged
/// writable and rewritten); `go_files` are their basenames (the declared
/// `in_place` outputs). The two are the same files viewed as addr vs. filename.
pub fn build_lint_fix_spec(
    addr: Addr,
    analyze_addr: &Addr,
    src_addrs: &[String],
    go_files: &[String],
    config_addr: Option<&Addr>,
) -> TargetSpec {
    let mut deps = BTreeMap::from([
        (
            "report".to_string(),
            Value::List(vec![Value::String(format!(
                "{}|report",
                analyze_addr.format()
            ))]),
        ),
        (
            String::new(),
            Value::List(src_addrs.iter().cloned().map(Value::String).collect()),
        ),
    ]);
    // Hash-only dep: a `.golangci.yml` change re-keys the fixer directly.
    if let Some(cfg) = config_addr {
        deps.insert(
            "config".to_string(),
            Value::List(vec![Value::String(cfg.format())]),
        );
    }

    let mut config: HashMap<String, Value> = HashMap::new();
    config.insert("deps".to_string(), Value::Map(deps.into_iter().collect()));
    config.insert(
        "out".to_string(),
        Value::Map(HashMap::from([(
            "src".to_string(),
            Value::List(go_files.iter().cloned().map(Value::String).collect()),
        )])),
    );

    TargetSpec {
        addr,
        driver: "go_lint_fix".to_string(),
        config,
        // The plain `lint` target is the FIXER, so it owns the plain labels:
        // `go-lint` (this language's) and `lint` (every language's), plus `fix` for
        // a fixers-only sweep. Checking without rewriting is `lint-check`.
        labels: vec!["go-lint".to_string(), "lint".to_string(), "fix".to_string()],
        transitive: Default::default(),
        approval: Default::default(),
    }
}

