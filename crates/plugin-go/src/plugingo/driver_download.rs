    #[test]
    fn copy_module_copies_the_tree_and_leaves_it_writable() {
        let dir = tempfile::tempdir().expect("tempdir");
        let src = dir.path().join("mod cache/c@v1");
        let dst = dir.path().join("out");
        std::fs::create_dir_all(src.join("sub/deep")).unwrap();
        std::fs::create_dir(&dst).unwrap();
        std::fs::write(src.join(".gitignore"), "hidden\n").unwrap();
        std::fs::write(src.join("sub/deep/a.go"), "package a\n").unwrap();
        std::fs::write(src.join("tool.sh"), "#!/bin/sh\n").unwrap();
        std::fs::set_permissions(
            src.join("sub/deep/a.go"),
            std::fs::Permissions::from_mode(0o444),
        )
        .unwrap();
        std::fs::set_permissions(src.join("tool.sh"), std::fs::Permissions::from_mode(0o555))
            .unwrap();

        copy_module(&src, &dst, &not_cancelled()).unwrap();

        assert_eq!(
            std::fs::read_to_string(dst.join(".gitignore")).unwrap(),
            "hidden\n"
        );
        assert_eq!(
            std::fs::read_to_string(dst.join("sub/deep/a.go")).unwrap(),
            "package a\n"
        );
        let mode = |p: &str| std::fs::metadata(dst.join(p)).unwrap().permissions().mode() & 0o700;
        assert_eq!(
            mode("sub/deep/a.go"),
            0o600,
            "read-only source, writable copy"
        );
        assert_eq!(mode("tool.sh"), 0o700, "the executable bit survives");
    }

