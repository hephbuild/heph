pub struct GoDownloadDriver {
    /// Default exec runner for `go`, from the plugin's `runner:` option. A
    /// target's own `runner` field overrides it. See [`crate::plugingo::runner`].
    default_runner: Option<String>,
    /// Host `go` resolved in whatever environment the runner names. Only ever
    /// touched by `gotool = "host"`.
    host_go: crate::plugingo::toolchain::HostGoCache,
}

impl GoDownloadDriver {
    pub fn new() -> Self {
        Self {
            default_runner: None,
            host_go: Default::default(),
        }
    }

    /// Set the driver-wide default runner (the plugin's `runner:` option).
    /// `None` and `Some("local")` both mean "spawn on the host".
    #[must_use]
    pub fn with_default_runner(mut self, runner: Option<String>) -> Self {
        self.default_runner = runner;
        self
    }
}

impl Default for GoDownloadDriver {
    fn default() -> Self {
        Self::new()
    }
}

/// Config for a `go.download` target (generated by the Go provider).
#[derive(Spec)]
struct GoDownloadSpec {
    /// Module path, e.g. `gopkg.in/yaml.v2`.
    module: String,
    /// Module version, e.g. `v2.4.0`.
    version: String,
    /// Go toolchain selector: a version, `host`, or a target address.
    go_version: String,
    /// Dependencies, grouped by name → list of target addresses. `gosdk` stages
    /// the toolchain.
    deps: HashMap<String, Vec<String>>,
    /// Exec runner `go` runs under: a target address producing a `runner.json`.
    /// Absent, or the literal `"local"`, spawns here. A hashed dependency, so
    /// changing the environment re-keys this target.
    runner: String,
}

#[derive(Clone, serde::Serialize, serde::Deserialize)]
struct GoDownloadDef {
    module: String,
    version: String,
    go_version: String,
    /// Absent from `Hash`: it reaches the cache key through the hashout of the
    /// input `parse` emits. See [`crate::plugingo::runner`].
    runner: Option<TargetAddr>,
}

/// Bump to invalidate every cached module tree when what this driver copies out
/// of a module changes.
const GO_DOWNLOAD_FORMAT_VERSION: u32 = 1;

impl Hash for GoDownloadDef {
    fn hash<H: Hasher>(&self, state: &mut H) {
        GO_DOWNLOAD_FORMAT_VERSION.hash(state);
        self.module.hash(state);
        self.version.hash(state);
        self.go_version.hash(state);
    }
}

/// Host environment `go mod download` may see.
///
/// These say where module bytes come from and how to reach them, and those bytes
/// are verified against the checksum database, so none of them reach a hash.
///
/// `GOMODCACHE` is deliberately absent: the module cache is heph's scratch.
const MODULE_FETCH_PASS_ENV: &[&str] = &[
    "HOME",
    "GOPATH",
    "GOCACHE",
    "GOPROXY",
    "GONOSUMDB",
    "GOSUMDB",
    "GOFLAGS",
    "GOPRIVATE",
    "GONOSUMCHECK",
    "GOINSECURE",
];

/// `host` looks a variable up in the host environment. Injected so a test can
/// describe an environment without mutating the process's own.
fn download_env(
    go_version: &str,
    goroot: &Path,
    gomodcache: &Path,
    host: impl Fn(&str) -> Option<String>,
) -> HashMap<String, String> {
    let mut env: HashMap<String, String> = HashMap::new();
    for name in MODULE_FETCH_PASS_ENV {
        if let Some(v) = host(name) {
            env.insert((*name).to_string(), v);
        }
    }
    // A non-hermetic `go` may be a wrapper that needs `PATH`. A hermetic one is
    // PATH-independent, and the host's directories stay out.
    if !matches!(
        crate::plugingo::toolchain::classify(go_version),
        crate::plugingo::toolchain::Toolchain::Hermetic(_)
    ) && let Some(v) = host("PATH")
    {
        env.insert("PATH".to_string(), v);
    }
    env.insert("GOROOT".to_string(), goroot.to_string_lossy().into_owned());
    env.insert(
        "GOMODCACHE".to_string(),
        gomodcache.to_string_lossy().into_owned(),
    );
    env.insert("GOTOOLCHAIN".to_string(), "local".to_string());
    env.insert("GOWORK".to_string(), "off".to_string());
    env.insert("CGO_ENABLED".to_string(), "0".to_string());
    env
}

/// The module directory out of `go mod download -json`'s stdout.
fn parse_module_dir(stdout: &[u8]) -> anyhow::Result<PathBuf> {
    #[derive(serde::Deserialize)]
    struct ModuleDownload {
        #[serde(rename = "Dir")]
        dir: Option<String>,
    }

    let parsed: ModuleDownload = serde_json::from_slice(stdout).with_context(|| {
        format!(
            "parse `go mod download -json` output: {}",
            String::from_utf8_lossy(stdout)
        )
    })?;
    match parsed.dir {
        Some(dir) if !dir.is_empty() => Ok(PathBuf::from(dir)),
        _ => anyhow::bail!(
            "go mod download produced no Dir: {}",
            String::from_utf8_lossy(stdout)
        ),
    }
}

/// Run `go mod download` for one module and return the directory `go` put it in.
async fn fetch_module(
    go_bin: &Path,
    mod_at_ver: &str,
    env: &HashMap<String, String>,
    cwd: &Path,
    runner: hexecrunner::RunnerRef<'_>,
    ctoken: &(dyn Cancellable + Send + Sync),
) -> anyhow::Result<PathBuf> {
    // Without a go.mod here, Go would walk up and read one above the sandbox.
    let stub = cwd.join("go.mod");
    std::fs::write(&stub, "module heph_ignore\n")
        .with_context(|| format!("write stub {}", stub.display()))?;

    let spec = proc_exec::Spec {
        program: go_bin.to_path_buf(),
        args: ["mod", "download", "-modcacherw", "-json", mod_at_ver]
            .iter()
            .map(OsString::from)
            .collect(),
        env: env
            .iter()
            .map(|(k, v)| (OsString::from(k), OsString::from(v)))
            .collect(),
        cwd: cwd.to_path_buf(),
        stdin: proc_exec::StdioSpec::Null,
        stdout: proc_exec::StdioSpec::Piped,
        stderr: proc_exec::StdioSpec::Piped,
        setsid: false,
        ctty: false,
    };
    let output = hexecrunner::output(runner, spec, ctoken)
        .await
        .with_context(|| format!("wait for go mod download {mod_at_ver}"))?;
    if !output.status.success() {
        anyhow::bail!(
            "go mod download {mod_at_ver} failed ({}):\n{}",
            output.status,
            crate::plugingo::driver_compile::go_failure_detail(
                &String::from_utf8_lossy(&output.stdout),
                &String::from_utf8_lossy(&output.stderr),
            )
        );
    }

    // Removed before the copy: the module's own go.mod belongs at this path.
    std::fs::remove_file(&stub).with_context(|| format!("remove stub {}", stub.display()))?;
    parse_module_dir(&output.stdout)
}

/// Copy a module tree, leaving every file owner-writable.
///
/// Go's module cache files are read-only even under `-modcacherw`, which only
/// covers directories.
///
/// File contents go through `io::copy` rather than `std::fs::copy`, which on
/// macOS also copies xattrs (`com.apple.quarantine` on Go's cache files), and a
/// FUSE overlay rejects xattr writes with EPERM.
fn copy_module(src: &Path, dst: &Path) -> anyhow::Result<()> {
    let entries = std::fs::read_dir(src).with_context(|| format!("read {}", src.display()))?;
    for entry in entries {
        let entry = entry.with_context(|| format!("read entry of {}", src.display()))?;
        let from = entry.path();
        let to = dst.join(entry.file_name());
        let file_type = entry
            .file_type()
            .with_context(|| format!("stat {}", from.display()))?;

        if file_type.is_dir() {
            std::fs::create_dir_all(&to).with_context(|| format!("mkdir {}", to.display()))?;
            copy_module(&from, &to)?;
        } else if file_type.is_symlink() {
            let target = std::fs::read_link(&from)
                .with_context(|| format!("readlink {}", from.display()))?;
            std::os::unix::fs::symlink(&target, &to)
                .with_context(|| format!("symlink {}", to.display()))?;
        } else {
            let mut reader =
                std::fs::File::open(&from).with_context(|| format!("open {}", from.display()))?;
            let mode = reader
                .metadata()
                .with_context(|| format!("stat {}", from.display()))?
                .permissions()
                .mode();
            let mut writer = std::fs::OpenOptions::new()
                .write(true)
                .create(true)
                .truncate(true)
                .mode(mode | 0o200)
                .open(&to)
                .with_context(|| format!("create {}", to.display()))?;
            std::io::copy(&mut reader, &mut writer)
                .with_context(|| format!("copy {} to {}", from.display(), to.display()))?;
        }
    }
    Ok(())
}

#[async_trait]
impl ManagedDriver for GoDownloadDriver {
    fn config(&self, _req: ConfigRequest) -> anyhow::Result<ConfigResponse> {
        Ok(ConfigResponse {
            name: "download".to_string(),
        })
    }

    fn schema(&self) -> hplugin::driver::DriverSchema {
        GoDownloadSpec::schema()
    }

    async fn parse(
        &self,
        req: ParseRequest,
        _ctoken: &(dyn Cancellable + Send + Sync),
    ) -> anyhow::Result<ParseResponse> {
        let pkg = req.target_spec.addr.package.clone();
        let spec =
            GoDownloadSpec::from(&req.target_spec.config).context("parse go.download config")?;
        anyhow::ensure!(!spec.module.is_empty(), "go.download: `module` is required");
        anyhow::ensure!(
            !spec.version.is_empty(),
            "go.download: `version` is required"
        );

        let mut inputs: Vec<Input> = Vec::new();
        // Sorted so `HashMap` iteration order cannot reach the input list.
        let mut groups: Vec<&String> = spec.deps.keys().collect();
        groups.sort();
        for group in groups {
            let annotations = if group == crate::plugingo::addr_util::GO_SDK_DEP_GROUP {
                BTreeMap::from([(
                    hdriver_support::stage::READ_ONLY_ANNOTATION.to_string(),
                    "true".to_string(),
                )])
            } else {
                BTreeMap::new()
            };
            for (i, addr) in spec.deps.get(group).into_iter().flatten().enumerate() {
                inputs.push(Input {
                    r#ref: TargetAddr::parse(addr, &pkg)
                        .with_context(|| format!("parse dep addr {addr}"))?,
                    mode: InputMode::Standard,
                    origin_id: format!("dep|{group}|{i}"),
                    annotations: annotations.clone(),
                    hashed: true,
                    runtime: true,
                });
            }
        }

        let (runner, runner_input) = crate::plugingo::runner::parse_runner_with_default(
            &spec.runner,
            self.default_runner.as_deref(),
            &pkg,
        )?;
        inputs.extend(runner_input);

        // The shared module cache: unhashed, because the bytes `go` hands back are
        // checksum-verified whether the cache was warm or cold.
        inputs.push(Input {
            r#ref: TargetAddr {
                r#ref: crate::plugingo::gocache::modcache_addr(),
                output: None,
                filters: vec![],
            },
            mode: InputMode::Standard,
            origin_id: format!("{}|0", hdriver_support::scratch::SCRATCH_ORIGIN_PREFIX),
            annotations: BTreeMap::from([(
                hdriver_support::scratch::SCRATCH_ANNOTATION.to_string(),
                "true".to_string(),
            )]),
            hashed: false,
            runtime: false,
        });

        let def = GoDownloadDef {
            module: spec.module,
            version: spec.version,
            go_version: spec.go_version,
            runner,
        };
        let hash = {
            let mut h = DebugHasher::new(Xxh3Default::new(), || {
                format!("go_download_{}", req.target_spec.addr.format())
            });
            def.hash(&mut h);
            format!("{:x}", h.finish()).into_bytes()
        };

        let glob = hmodel::htpkg::join_rel_checked(pkg.as_str(), "**/*")
            .context("resolve go.download output glob")?;

        Ok(ParseResponse {
            target_def: TargetDef {
                addr: req.target_spec.addr.clone(),
                labels: req.target_spec.labels.clone(),
                raw_def: Arc::new(def),
                inputs,
                outputs: vec![Output {
                    group: String::new(),
                    paths: vec![OutputPath {
                        content: Content::Glob(glob),
                        codegen_tree: CodegenMode::None,
                        collect: true,
                    }],
                }],
                cache: CacheConfig::on(true),
                hash,
                ..Default::default()
            },
        })
    }

    async fn apply_transitive(
        &self,
        req: ApplyTransitiveRequest,
        _ctoken: &(dyn Cancellable + Send + Sync),
    ) -> anyhow::Result<ApplyTransitiveResponse> {
        Ok(ApplyTransitiveResponse {
            target_def: req.target_def,
        })
    }

    async fn run<'a, 'io>(
        &self,
        req: ManagedRunRequest<'a, 'io>,
        ctoken: &(dyn Cancellable + Send + Sync),
    ) -> anyhow::Result<ManagedRunResponse> {
        let def = req.request.target.def_de::<GoDownloadDef>();
        let runner =
            crate::plugingo::runner::runner_ref(req.request.request_id, def.runner.as_ref());
        let (goroot, go_bin) = crate::plugingo::toolchain::resolve_toolchain_go(
            &def.go_version,
            &req.inputs,
            &req.sandbox_ws_dir,
            "go.download",
            runner,
            &self.host_go,
            ctoken,
        )
        .await?;

        let gomodcache = req
            .request
            .scratch
            .iter()
            .find(|m| m.env == "GOMODCACHE")
            .map(|m| m.dir.clone())
            .context(
                "no GOMODCACHE scratch mount: the host resolves and locks one for every \
                 target that references the shared cache, and `--no-scratch` supplies an \
                 empty one rather than none",
            )?;

        let env = download_env(&def.go_version, &goroot, &gomodcache, |n| {
            std::env::var(n).ok()
        });
        let mod_at_ver = format!("{}@{}", def.module, def.version);
        let module_dir = fetch_module(
            &go_bin,
            &mod_at_ver,
            &env,
            &req.sandbox_pkg_dir,
            runner,
            ctoken,
        )
        .await?;

        let pkg_dir = req.sandbox_pkg_dir.clone();
        tokio::task::spawn_blocking(
            enclose!((module_dir) move || copy_module(&module_dir, &pkg_dir)),
        )
        .await
        .context("join module copy")?
        .with_context(|| format!("copy {mod_at_ver} from {}", module_dir.display()))?;

        Ok(ManagedRunResponse { artifacts: vec![] })
    }
}

